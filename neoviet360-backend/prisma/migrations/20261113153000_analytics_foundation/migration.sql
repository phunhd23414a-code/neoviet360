-- Analytics foundation.
-- These tables are intentionally separate from Prisma application models:
-- the application owns public.* while analytics owns reporting tables.

CREATE SCHEMA IF NOT EXISTS analytics;

CREATE TABLE IF NOT EXISTS analytics.dim_date (
    date_key INTEGER PRIMARY KEY,
    full_date DATE NOT NULL UNIQUE,
    year SMALLINT NOT NULL,
    quarter SMALLINT NOT NULL CHECK (quarter BETWEEN 1 AND 4),
    month SMALLINT NOT NULL CHECK (month BETWEEN 1 AND 12),
    week SMALLINT NOT NULL CHECK (week BETWEEN 1 AND 53),
    day_of_week SMALLINT NOT NULL CHECK (day_of_week BETWEEN 0 AND 6),
    is_weekend BOOLEAN NOT NULL,
    is_month_start BOOLEAN NOT NULL,
    is_month_end BOOLEAN NOT NULL
);

CREATE TABLE IF NOT EXISTS analytics.dim_user (
    user_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id TEXT NOT NULL UNIQUE,
    email TEXT,
    created_date DATE,
    source_loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS analytics.dim_category (
    category_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    category_name TEXT NOT NULL UNIQUE,
    category_group TEXT NOT NULL,
    is_income BOOLEAN NOT NULL DEFAULT FALSE,
    is_expense BOOLEAN NOT NULL DEFAULT FALSE,
    source_loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS analytics.dim_account (
    account_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    account_id TEXT NOT NULL UNIQUE,
    user_id TEXT NOT NULL,
    account_type TEXT NOT NULL,
    currency TEXT NOT NULL,
    source_loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE TABLE IF NOT EXISTS analytics.fact_transaction (
    transaction_key BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    transaction_id TEXT NOT NULL UNIQUE,
    user_key BIGINT NOT NULL REFERENCES analytics.dim_user(user_key),
    date_key INTEGER NOT NULL REFERENCES analytics.dim_date(date_key),
    account_key BIGINT REFERENCES analytics.dim_account(account_key),
    category_key BIGINT NOT NULL REFERENCES analytics.dim_category(category_key),
    amount NUMERIC(18, 2) NOT NULL,
    currency TEXT NOT NULL,
    transaction_type TEXT NOT NULL,
    transaction_status TEXT NOT NULL,
    is_recurring BOOLEAN NOT NULL DEFAULT FALSE,
    is_anomaly BOOLEAN NOT NULL DEFAULT FALSE,
    source_created_at TIMESTAMPTZ NOT NULL,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

CREATE INDEX IF NOT EXISTS fact_transaction_user_date_idx
    ON analytics.fact_transaction (user_key, date_key);
CREATE INDEX IF NOT EXISTS fact_transaction_category_date_idx
    ON analytics.fact_transaction (category_key, date_key);
CREATE INDEX IF NOT EXISTS fact_transaction_type_idx
    ON analytics.fact_transaction (transaction_type, transaction_status);

CREATE TABLE IF NOT EXISTS analytics.fact_daily_cashflow (
    user_key BIGINT NOT NULL REFERENCES analytics.dim_user(user_key),
    date_key INTEGER NOT NULL REFERENCES analytics.dim_date(date_key),
    total_income NUMERIC(18, 2) NOT NULL DEFAULT 0,
    total_expense NUMERIC(18, 2) NOT NULL DEFAULT 0,
    net_cashflow NUMERIC(18, 2) NOT NULL DEFAULT 0,
    transaction_count INTEGER NOT NULL DEFAULT 0,
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_key, date_key)
);

CREATE TABLE IF NOT EXISTS analytics.fact_monthly_spending (
    user_key BIGINT NOT NULL REFERENCES analytics.dim_user(user_key),
    month_key INTEGER NOT NULL REFERENCES analytics.dim_date(date_key),
    total_income NUMERIC(18, 2) NOT NULL DEFAULT 0,
    total_expense NUMERIC(18, 2) NOT NULL DEFAULT 0,
    net_cashflow NUMERIC(18, 2) NOT NULL DEFAULT 0,
    saving_rate NUMERIC(7, 4),
    transaction_count INTEGER NOT NULL DEFAULT 0,
    budget_violation_rate NUMERIC(7, 4),
    loaded_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    PRIMARY KEY (user_key, month_key)
);

-- Seed the category dimension from the current application data. The insert
-- is idempotent and keeps unknown categories available for analysis.
INSERT INTO analytics.dim_category (
    category_name,
    category_group,
    is_income,
    is_expense
)
SELECT DISTINCT
    t.category,
    CASE
        WHEN t.type = 'INCOME'::"TransactionType" THEN 'INCOME'
        ELSE 'EXPENSE'
    END,
    t.type = 'INCOME'::"TransactionType",
    t.type = 'EXPENSE'::"TransactionType"
FROM public.transactions AS t
WHERE t.category IS NOT NULL
ON CONFLICT (category_name) DO NOTHING;
